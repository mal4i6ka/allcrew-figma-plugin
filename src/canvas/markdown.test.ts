import test from 'node:test'
import assert from 'node:assert/strict'
import { anchorSlug, parseInline, parseMarkdown, plainText, splitRow } from './markdown.ts'

test('inline marks become runs, and words that only look like marks stay words', () => {
  assert.deepEqual(parseInline('Use **bold** and *it* with `code` — see [docs](https://x.dev).'), [
    { text: 'Use ' },
    { text: 'bold', bold: true },
    { text: ' and ' },
    { text: 'it', italic: true },
    { text: ' with ' },
    { text: 'code', code: true },
    { text: ' — see ' },
    { text: 'docs', href: 'https://x.dev' },
    { text: '.' },
  ])
  assert.deepEqual(parseInline('snake_case_name and 2 * 3 * 4'), [{ text: 'snake_case_name and 2 * 3 * 4' }])
  assert.deepEqual(parseInline('**Behaviour — _implement_ this:**'), [
    { text: 'Behaviour — ', bold: true },
    { text: 'implement', bold: true, italic: true },
    { text: ' this:', bold: true },
  ])
  assert.deepEqual(parseInline('<https://figma.com> and \\*not\\*'), [
    { text: 'https://figma.com', href: 'https://figma.com' },
    { text: ' and *not*' },
  ])
  assert.deepEqual(parseInline('a<br>b <a id="x"></a>'), [{ text: 'a\nb ' }])
  assert.deepEqual(parseInline('[`Button`](#button)'), [{ text: 'Button', code: true, href: '#button' }])
})

test('headings carry the anchor GitHub would give them', () => {
  assert.equal(anchorSlug('Components — My File'), 'components--my-file')
  assert.equal(anchorSlug('Цвета и `токены`'), 'цвета-и-токены')
  const [heading] = parseMarkdown('## Button / Primary ##')
  assert.equal(heading.kind, 'heading')
  assert.equal(heading.kind === 'heading' && heading.level, 2)
  assert.equal(heading.kind === 'heading' && heading.slug, 'button--primary')
})

test('the blocks the export writes come back in order', () => {
  const blocks = parseMarkdown(
    [
      '# Components — F',
      '',
      '<!-- GENERATED by the plugin.',
      '     Do not hand-edit. -->',
      '',
      'First line',
      'continues here.',
      '',
      '<a id="button-2"></a>',
      '## Button',
      '',
      '![Button](previews/button.png)',
      '',
      '> **For designers:** a quote',
      '> over two lines',
      '',
      '| Name | Value |',
      '| --- | ---: |',
      '| `a\\|b` | **1** |',
      '| c |',
      '',
      '```ts',
      'const x = 1',
      '',
      'x++',
      '```',
      '',
      '---',
    ].join('\n')
  )
  assert.deepEqual(
    blocks.map((block) => block.kind),
    ['heading', 'paragraph', 'anchor', 'heading', 'image', 'quote', 'table', 'code', 'rule']
  )
  assert.equal(blocks[1].kind === 'paragraph' && plainText(blocks[1].runs), 'First line continues here.')
  assert.deepEqual(blocks[2], { kind: 'anchor', id: 'button-2' })
  assert.deepEqual(blocks[4], { kind: 'image', alt: 'Button', src: 'previews/button.png' })
  const quote = blocks[5]
  assert.equal(quote.kind === 'quote' && quote.blocks.length, 1)
  const table = blocks[6]
  assert.ok(table.kind === 'table')
  assert.deepEqual(table.align, ['left', 'right'])
  assert.deepEqual(table.rows[0][0], [{ text: 'a|b', code: true }])
  // A short row is padded to the header, not left ragged.
  assert.deepEqual(table.rows[1], [[{ text: 'c' }], []])
  assert.deepEqual(blocks[7], { kind: 'code', lang: 'ts', text: 'const x = 1\n\nx++' })
})

test('lists keep their nesting, numbering and tasks', () => {
  const [list, after] = parseMarkdown('3. one\n   still one\n4. two\n   - nested\n\n5. three\n\nAfter.')
  assert.ok(list.kind === 'list')
  assert.equal(list.ordered, true)
  assert.equal(list.start, 3)
  assert.deepEqual(
    list.items.map((item) => [plainText(item.runs), item.depth]),
    [['one still one', 0], ['two', 0], ['nested', 1], ['three', 0]]
  )
  assert.equal(after.kind, 'paragraph')
  const [tasks] = parseMarkdown('- [x] done\n- [ ] open')
  assert.ok(tasks.kind === 'list')
  assert.deepEqual(tasks.items.map((item) => item.checked), [true, false])
})

test('a table row splits on bars outside code only', () => {
  assert.deepEqual(splitRow('| `x | y` | b \\| c |'), ['`x | y`', 'b | c'])
})
