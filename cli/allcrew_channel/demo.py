_VIEWS_PY = f'''# {MARKER} — browse the exported pages; navMap feeds the {{{{ navMap.nav_… }}}}
# links the plugin emits for Figma NAVIGATE reactions.
import re

from django.conf import settings
from django.http import Http404
from django.shortcuts import render


def _page_templates():
    pages_dir = settings.BASE_DIR / "templates" / "pages"
    if not pages_dir.is_dir():
        return []
    return sorted(path.name for path in pages_dir.glob("*.html"))


def _nav_map():
    # pages/one-main--4110-62538.html → nav_4110_62538: the template filename ends with the
    # source frame's id slug (the plugin's navMapKey convention).
    nav = {{}}
    for name in _page_templates():
        stem = name[: -len(".html")]
        if "--" not in stem:
            continue
        id_slug = stem.rsplit("--", 1)[1]
        key = "nav_" + re.sub(r"[^A-Za-z0-9]+", "_", id_slug).strip("_")
        nav[key] = f"/page/{{name}}"
    return nav


def index(request):
    return render(request, "demo/index.html", {{"pages": _page_templates()}})


def page(request, name):
    if name not in _page_templates():
        raise Http404(f"no exported page template named {{name}}")
    return render(request, f"pages/{{name}}", {{"navMap": _nav_map()}})
'''

